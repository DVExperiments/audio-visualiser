// Generates docs/PRESET-MATHS.md from the same explanation specs the in-app "How it works" panel
// uses (so the document and the app cannot disagree). Run: npm run docs:maths
import fs from 'node:fs';
import { EXPLAIN } from '../src/renderer/explain/specs.mjs';
import { WARP_PRESETS, computeWarp, explainWarp, describeDecay } from '../src/renderer/engine/warp-model.mjs';
import { MappingSet, mappingTex } from '../src/renderer/engine/mapping.mjs';
import { MORPH_MAPPINGS } from '../src/renderer/visualizations/experimental/morph-model.mjs';
import { COMMON_MAPPINGS } from '../test/helpers/common-mappings.mjs';

const out = [];
const P = (...l) => out.push(...l);
const steps = (spec) => spec.steps.forEach((s, i) => {
  P(`#### ${i + 1}. ${s.title}`, '', s.why, '');
  for (const t of s.tex) P('$$', t, '$$', '');
  if (s.vars.length) { P('| Symbol | Meaning |', '|---|---|'); for (const [sym, m] of s.vars) P(`| $${sym}$ | ${m.replace(/\|/g, '\\|')} |`); P(''); }
});
const mappings = (title, specs) => {
  P(`### ${title}`, '');
  const set = new MappingSet(specs);
  for (const [name, m] of Object.entries(set.mappings)) P('$$', mappingTex(name, m.spec), '$$', '');
};

P('# Preset mathematics', '',
  '*Generated by `npm run docs:maths` from the same specifications as the in-app **How it works** panel (press E). Do not edit by hand.*', '',
  'Each preset lists what it draws, the equations it runs every frame, and what every symbol means. In the app the same panel also shows the live value of every symbol as the music plays.', '');

P('## Battery-inspired: wave and warp', '',
  'These looks share one recipe: draw the waveform, warp the previous frame, fade each colour channel at its own rate, fold for symmetry, present. The colour of the trails comes from step 3 — when red outlasts green and green outlasts blue, a white line ages through yellow, orange and red; reversing the order gives ice.', '');
P('| Preset | Look | Symmetry | Half-lives r, g, b (s) | Colour journey |', '|---|---|---|---|---|');
for (const d of WARP_PRESETS) {
  const live = computeWarp(d, {});
  P(`| ${d.name} | ${d.look} | ${live.symName}${live.symName === 'kaleido' ? ` (${live.fold})` : ''} | ${live.half.map((h) => h.toFixed(2)).join(', ')} | ${describeDecay(live.half).split(':').slice(-1)[0].trim()} |`);
}
P('');
for (const d of WARP_PRESETS) {
  const spec = explainWarp(d, () => ({ ...computeWarp(d, {}), gain: 1, dt: 1 / 60 }));
  P(`### ${d.name}`, '', spec.summary, '');
  steps(spec);
}
const groups = [
  ['Bars & Waves (measurement)', ['instruments', 'spectrum', 'scope', 'stereo', 'circular', 'ridgeline', 'vu', 'terrain', 'phosphor', 'analysis', 'mashup']],
  ['Experimental', ['morph', 'swarm']],
  ['Alchemy-inspired', ['liquid-ribbons', 'spiral-elixir', 'acid-warp', 'plasma-prism', 'julia-bloom', 'hyper-tunnel', 'rainbow-mandala']],
  ['Battery-inspired: classic', ['polygon-pulse', 'star-tunnel']],
  ['Ambience-inspired', ['water', 'swirl', 'nebula', 'aurora']],
];
for (const [g, ids] of groups) {
  P(`## ${g}`, '');
  for (const id of ids) { const spec = EXPLAIN[id](() => ({ frame: null, drives: {}, r: null })); P(`### ${spec.title}`, '', spec.summary, ''); steps(spec); }
}
P('## Audio → drives', '', 'How the analysis features become the drives used above. Pulses measure how far each band rises above its own recent typical level (docs/DSP.md), which is what carries the beat.', '');
mappings('Shared by the feedback collections', COMMON_MAPPINGS);
mappings('Morph', MORPH_MAPPINGS);

fs.writeFileSync(new URL('../../../docs/PRESET-MATHS.md', import.meta.url), out.join('\n'));
console.log(`docs/PRESET-MATHS.md: ${out.length} lines`);
